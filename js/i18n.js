  /** Translate `key`, replacing each %s / %d with the next argument. */
  BOOM.t = function (key, ...args) {
    const lang = (BOOM.Settings && BOOM.Settings.data.lang) || 'vi';
    let text = STRINGS[lang][key] ?? STRINGS.vi[key] ?? key;
    for (const a of args) text = text.replace(/%[sd]/, a);
    return text;
  };

  /** Fill every [data-i18n] / [data-i18n-placeholder] element under `root`. */
  BOOM.applyI18n = function (root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = BOOM.t(el.dataset.i18n)));
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = BOOM.t(el.dataset.i18nPlaceholder)));
    document.documentElement.lang = BOOM.Settings.data.lang;
  };
